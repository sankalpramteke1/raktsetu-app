// Helper to generate full bag count matching stock numbers for realistic deep scroll
export const getBagsForGroup = (group: BloodGroup): BloodBag[] => {
  const matching = BLOOD_BAGS.filter((b) => b.bloodGroup === group);
  // If matching count is less than displayed stock, generate supplementary bags deterministically
  if (matching.length < 8) {
    const supplement: BloodBag[] = [];
    for (let i = matching.length; i < 18; i++) {
      const day = 24 - (i % 12);
      const dayStr = day < 10 ? `0${day}` : `${day}`;
      const expDay = ((day + 28) % 30) + 1;
      const expDayStr = expDay < 10 ? `0${expDay}` : `${expDay}`;
      const statusList: BloodBag['status'][] = ['Available', 'Available', 'Available', 'Reserved', 'Available'];
      const st = statusList[i % statusList.length];

      supplement.push({
        bagId: `BAG-2026-08${530 + i}`,
        bloodGroup: group,
        collectionDate: `${dayStr} Sep 2026`,
        expiryDate: `${expDayStr} Oct 2026`,
        status: st,
        storage: group.includes('O') ? 'Refrigerator 01' : 'Refrigerator 02',
        componentType: i % 3 === 0 ? 'Whole Blood' : i % 3 === 1 ? 'Packed RBC' : 'Platelet Concentrate',
        volumeMl: i % 2 === 0 ? 350 : 450,
        donorId: `DON-34${10 + (i % 35)}`,
        testedSafe: true,
      });
    }
    return [...matching, ...supplement];
  }
  return matching;
};
